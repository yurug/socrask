#!/usr/bin/env python3
"""roadmap-check — milestones, schedule and execution risks for complex projects.

A project with more than one slice gets a roadmap the engineer approves before
work starts: milestones with acceptance cases, a schedule that shows parallel
waves and the critical path, and the execution risks with the task that retires
each one. The data lives in the ledger (`project.roadmap`); the tables in
`kb/roadmap.md` are generated from it, between markers, so they cannot drift.

Usage:
    roadmap-check.py [--ledger kb/work/ledger.json] [--doc kb/roadmap.md]
    roadmap-check.py --write          regenerate the tables in the doc
    roadmap-check.py --digest PROJECT print the digest an approval must cite

Ledger shape, on a project:
    "roadmap": {
      "milestones": [{"id", "title", "tasks": [...], "cases": [...], "retires": [risk ids]}],
      "risks": [{"id", "statement", "probability": "low|medium|high",
                 "impact": "low|medium|high", "retired_by": task, "blocks": [tasks]}],
      "approval": {"status": "pending|human-complete|degraded-authorized",
                   "digest": "<from --digest>", "evidence": {"kind": "human-event",
                   "ref": "forebrief:<card-id>"}}
    }
Tasks can carry `estimate_hours` (agent-hours) to weight the critical path.

Exit code: 0 = clean (warnings allowed), 1 = errors.

Checks (E = error, W = warning):
    E-cycle      the project's task dependencies contain a cycle
    E-milestone  a milestone without acceptance cases, or naming an unknown task/risk
    E-risk       a risk without a known retiring task, or a blocked task that does
                 not depend (transitively) on the task that retires the risk
    E-approval   work on the project has started (a task active, reopened or
                 closed) without an approval that is human-complete or
                 degraded-authorized, cites evidence, and matches the current digest
    E-doc        the generated tables in the doc are missing or stale
    W-estimate   tasks without estimate_hours (counted as 1 hour)
    W-late-risk  a high risk whose retiring task cannot start in the first wave

What this does NOT check: that estimates are right, that the risk list is
complete, or that the human evidence is authentic.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys

BEGIN, END = "<!-- roadmap:begin (generated by roadmap-check.py --write) -->", "<!-- roadmap:end -->"
STARTED = {"active", "reopened", "closed"}
APPROVED = {"human-complete", "degraded-authorized"}


def project_tasks(ledger, project):
    plans = {p["id"] for p in ledger.get("plans", []) if p.get("project") == project}
    return {t["id"]: t for t in ledger.get("tasks", []) if t.get("plan") in plans}


def digest(ledger, project):
    road = dict(project.get("roadmap", {}))
    road.pop("approval", None)
    tasks = project_tasks(ledger, project["id"])
    shape = {"roadmap": road, "tasks": {i: {"depends_on": sorted(t.get("depends_on", [])),
                                            "estimate_hours": t.get("estimate_hours")}
                                        for i, t in sorted(tasks.items())}}
    return hashlib.sha256(json.dumps(shape, sort_keys=True).encode()).hexdigest()[:16]


def waves(tasks):
    """Topological levels inside the project; None on a cycle."""
    level, remaining = {}, dict(tasks)
    while remaining:
        ready = [i for i, t in remaining.items()
                 if all(d in level or d not in tasks for d in t.get("depends_on", []))]
        if not ready:
            return None
        for i in ready:
            deps = [level[d] for d in remaining[i].get("depends_on", []) if d in level]
            level[i] = 1 + max(deps, default=0)
            del remaining[i]
    out = {}
    for i, n in level.items():
        out.setdefault(n, []).append(i)
    return [sorted(out[n]) for n in sorted(out)]


def critical_path(tasks, order):
    hours = {i: float(t.get("estimate_hours") or 1) for i, t in tasks.items()}
    best, prev = {}, {}
    for wave in order:
        for i in wave:
            deps = [d for d in tasks[i].get("depends_on", []) if d in tasks]
            p = max(deps, key=lambda d: best[d], default=None)
            best[i] = hours[i] + (best[p] if p else 0)
            prev[i] = p
    end = max(best, key=lambda i: best[i])
    path = [end]
    while prev[path[-1]]:
        path.append(prev[path[-1]])
    return list(reversed(path)), best[end], sum(hours.values())


def ancestors(tasks, task):
    seen, stack = set(), list(tasks.get(task, {}).get("depends_on", []))
    while stack:
        d = stack.pop()
        if d not in seen and d in tasks:
            seen.add(d)
            stack.extend(tasks[d].get("depends_on", []))
    return seen


def render(project, tasks, order):
    road = project["roadmap"]
    path, length, total = critical_path(tasks, order)
    width = max(len(w) for w in order)
    lines = [BEGIN, f"### {project['id']}", "", "| Milestone | Tasks | Acceptance cases | Retires |",
             "|---|---|---|---|"]
    for m in road.get("milestones", []):
        lines.append(f"| {m['id']}: {m.get('title', '')} | {', '.join(m.get('tasks', []))} | "
                     f"{', '.join(m.get('cases', []))} | {', '.join(m.get('retires', [])) or '-'} |")
    lines += ["", "| Wave | Tasks in parallel |", "|---|---|"]
    lines += [f"| {n} | {', '.join(w)} |" for n, w in enumerate(order, 1)]
    wip = project.get("wip_limit")
    lines += ["", f"Critical path: {' -> '.join(path)} ({length:g} h of {total:g} h total). "
                  f"Widest wave: {width} tasks" + (f"; WIP limit {wip}." if wip else "."),
              "", "| Risk | Probability | Impact | Retired by | Blocks |", "|---|---|---|---|---|"]
    for r in road.get("risks", []):
        lines.append(f"| {r['id']}: {r.get('statement', '')} | {r.get('probability', '?')} | "
                     f"{r.get('impact', '?')} | {r.get('retired_by', '-')} | "
                     f"{', '.join(r.get('blocks', [])) or '-'} |")
    return "\n".join(lines + [END])


def check_project(ledger, project):
    errors, warnings = [], []
    pid, road = project["id"], project["roadmap"]
    tasks = project_tasks(ledger, pid)
    order = waves(tasks)
    if order is None:
        return [f"E-cycle: {pid} task dependencies contain a cycle"], [], None
    if not tasks:
        return [f"E-milestone: {pid} has a roadmap but no tasks"], [], None
    risk_ids = {r.get("id") for r in road.get("risks", [])}
    for m in road.get("milestones", []):
        if not m.get("cases"):
            errors.append(f"E-milestone: {pid}/{m.get('id')} has no acceptance cases")
        for t in m.get("tasks", []):
            if t not in tasks:
                errors.append(f"E-milestone: {pid}/{m.get('id')} names unknown task {t}")
        for r in m.get("retires", []):
            if r not in risk_ids:
                errors.append(f"E-milestone: {pid}/{m.get('id')} retires unknown risk {r}")
    first_wave = set(order[0])
    for r in road.get("risks", []):
        rid, by = r.get("id"), r.get("retired_by")
        if by not in tasks:
            errors.append(f"E-risk: {pid}/{rid} has no known retiring task (`retired_by`)")
            continue
        for b in r.get("blocks", []):
            if b not in tasks:
                errors.append(f"E-risk: {pid}/{rid} blocks unknown task {b}")
            elif by not in ancestors(tasks, b):
                errors.append(f"E-risk: {pid}/{rid}: {b} does not depend on {by}, which retires "
                              "the risk; order the blocked work after the spike")
        if "high" in (r.get("probability"), r.get("impact")) and by not in first_wave:
            warnings.append(f"W-late-risk: {pid}/{rid} is high but {by} cannot start in the first "
                            "wave; consider a spike with no dependency")
    missing = sorted(i for i, t in tasks.items() if t.get("estimate_hours") is None)
    if missing:
        warnings.append(f"W-estimate: {pid} tasks without estimate_hours: {', '.join(missing)}")
    approval = road.get("approval", {})
    if any(t.get("status") in STARTED for t in tasks.values()):
        evidence = approval.get("evidence", {})
        if approval.get("status") not in APPROVED or not evidence.get("ref"):
            errors.append(f"E-approval: {pid} work has started without an approved roadmap "
                          "(status human-complete or degraded-authorized, with evidence)")
        elif approval.get("digest") != digest(ledger, project):
            errors.append(f"E-approval: {pid} roadmap changed since approval "
                          f"(digest {approval.get('digest')} != {digest(ledger, project)}); "
                          "present it again")
    return errors, warnings, render(project, tasks, order)


def main():
    parser = argparse.ArgumentParser(description="Check project roadmaps in the ledger.")
    parser.add_argument("--ledger", default="kb/work/ledger.json")
    parser.add_argument("--doc", default="kb/roadmap.md")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--digest")
    args = parser.parse_args()
    try:
        ledger = json.loads(Path(args.ledger).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"{args.ledger}: cannot read ledger: {exc}")
        return 1
    projects = [p for p in ledger.get("projects", []) if p.get("roadmap")]
    if args.digest:
        match = [p for p in projects if p["id"] == args.digest]
        if not match:
            print(f"{args.digest}: no project with a roadmap")
            return 1
        print(digest(ledger, match[0]))
        return 0

    errors, warnings, blocks = [], [], []
    for p in projects:
        e, w, block = check_project(ledger, p)
        errors += e
        warnings += w
        if block:
            blocks.append(block)
    doc = Path(args.doc)
    generated = "\n\n".join(blocks)
    if blocks:
        text = doc.read_text(encoding="utf-8") if doc.is_file() else ""
        start, end = text.find(BEGIN), text.rfind(END)
        current = text[start:end + len(END)] if start >= 0 and end >= 0 else None
        if args.write:
            body = (text[:start] + generated + text[end + len(END):] if current is not None
                    else text.rstrip() + ("\n\n" if text else "") + generated + "\n")
            doc.write_text(body, encoding="utf-8")
            print(f"{doc}: tables regenerated")
        elif current != generated:
            errors.append(f"E-doc: {doc} tables are missing or stale; run roadmap-check.py --write")
    for m in errors + warnings:
        print(m)
    print(f"roadmap-check: {len(projects)} roadmaps, {len(errors)} errors, {len(warnings)} warnings")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
